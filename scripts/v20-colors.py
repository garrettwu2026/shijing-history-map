"""Offline union adjacency graph; deterministic mineral palette assignment across all years."""
import json, math, collections
from pathlib import Path
from shapely.geometry import shape
from shapely.strtree import STRtree
R=Path(__file__).resolve().parents[1]
cat=json.loads((R/'data/polities.json').read_text());graph=collections.defaultdict(collections.Counter);areas=collections.Counter()
for row in json.loads((R/'data/snapshots.json').read_text()):
 fs=json.loads((R/'data'/row['file']).read_text())['features']; gs=[]; ids=[]
 for f in fs:
  pid=cat['index'].get(f['properties'].get('NAME'))
  if not pid or not f.get('geometry'):continue
  g=shape(f['geometry']);gs.append(g);ids.append(pid);areas[pid]+=g.area
 tree=STRtree(gs)
 for i,g in enumerate(gs):
  for j in tree.query(g.buffer(.10)):
   if j<=i or ids[i]==ids[j]:continue
   if g.distance(gs[j])<=.10:
    graph[ids[i]][ids[j]]+=1;graph[ids[j]][ids[i]]+=1
# No focus-gold hues. Limited lighter/darker mineral variants are deliberate.
palette=['#80b7ad','#c88682','#899bc3','#a6b783','#b18cb4','#76b5c8','#c39c87','#83a291','#adabbc','#b37793','#7295ad','#b9b99d','#619c9e','#a88c78','#8b8fb1','#b4a7ca','#94c3bc','#cf9ba5','#76936f','#c1b3a8','#91b1d0','#a77d6c','#8dada9','#bd94ae']
def rgb(h):return [int(h[i:i+2],16)/255 for i in (1,3,5)]
def blend(h):return [.53*c+.47*b for c,b in zip(rgb(h),rgb('#414b49'))]
def modes(c):
 r,g,b=c
 return [c,[.567*r+.433*g,.558*r+.442*g,.242*g+.758*b],[.625*r+.375*g,.7*r+.3*g,.3*g+.7*b],[sum(x*y for x,y in zip(c,[.213,.715,.072]))]*3]
cs=[modes(blend(c)) for c in palette]
def dist(a,b):return min(math.dist(a[0],b[0]),math.dist(a[1],b[1]),math.dist(a[2],b[2]))+.15*math.dist(a[3],b[3])
assigned={}
for pid in sorted(cat['polities'],key=lambda p:(-len(graph[p]),-areas[p],p)):
 used=[(assigned[n],w) for n,w in graph[pid].items() if n in assigned]
 if not used: idx=len(assigned)%len(palette)
 else:idx=max(range(len(palette)),key=lambda c:min(dist(cs[c],cs[n])/(1+.02*math.log1p(w)) for n,w in used))
 assigned[pid]=idx
out={p:palette[i] for p,i in sorted(assigned.items())}
(R/'modules/polity-colors.js').write_text('// Generated by scripts/v20-colors.py. Fixed identity lookup, no runtime adjacency scan.\nexport const polityColors='+json.dumps(out,ensure_ascii=False,separators=(',',':'))+';\n')
edges=[(p,n,w,dist(cs[assigned[p]],cs[assigned[n]])) for p in graph for n,w in graph[p].items() if p<n]
report={'palette':palette,'identities':len(out),'edges':len(edges),'method':'Across all snapshots, distance <= .10 degrees (includes simplification gaps); greedy maximin composite at alpha .53 over #414b49; normal/protan/deutan and luminance inspected. Not a claim of universal discriminability.','lowestEdges':sorted(edges,key=lambda e:e[3])[:30]}
(R/'artifacts/v20-color-report.json').write_text(json.dumps(report,ensure_ascii=False,indent=2))
print(len(out),'identities;',len(edges),'union adjacency edges')
