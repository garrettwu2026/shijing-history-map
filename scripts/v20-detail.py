"""Build lazy gzip detail using the same upstream shapes, retaining local identities.
Raw downloads stay in ignored artifacts. Regenerate explicitly, never during build.
"""
import json,gzip,hashlib,subprocess,collections
from pathlib import Path
from shapely.geometry import shape,mapping
from shapely.ops import unary_union
R=Path(__file__).resolve().parents[1];cache=R/'artifacts/v20-upstream';out=R/'data/detail';out.mkdir(exist_ok=True)
cache.mkdir(parents=True,exist_ok=True)
commit='4b5039e50d8d2464b065bd76ad6086cd4597108d';report={};manifest={}
def rounded(x):
 if isinstance(x,float):return round(x,4)
 if isinstance(x,(list,tuple)):return [rounded(v) for v in x]
 if isinstance(x,dict):return {k:rounded(v) for k,v in x.items()}
 return x
def emit(name,data):
 raw=json.dumps(rounded(data),ensure_ascii=False,separators=(',',':')).encode();packed=gzip.compress(raw,mtime=0);fn=name+'.'+hashlib.sha256(packed).hexdigest()[:12]+'.json.gz';(out/fn).write_bytes(packed);manifest[name]=fn
 return {'jsonBytes':len(raw),'gzipBytes':len(packed)}
for row in json.loads((R/'data/snapshots.json').read_text()):
 name=row['file'];p=cache/name
 if not p.exists():subprocess.run(['curl','-fLsS','--retry','2',f'https://raw.githubusercontent.com/aourednik/historical-basemaps/{commit}/geojson/{name}','-o',str(p)],check=True)
 old=json.loads((R/'data'/name).read_text());up=json.loads(p.read_text());byname=collections.defaultdict(list)
 for f in up['features']:
  if f.get('geometry'):byname[f['properties'].get('NAME','')].append(shape(f['geometry']))
 features=[];matched=0;fallback=[];partsMatched=0
 for i,f in enumerate(old['features']):
  if not f.get('geometry'):features.append({'type':'Feature','geometry':f['geometry'],'properties':{'index':i}});continue
  g=shape(f['geometry']);candidates=byname[f['properties'].get('NAME','')]
  # Local coordinates are upstream vertices rounded to .01 degrees. Match each
  # retained polygon by an EXACT vertex subset, avoiding new islands/territories.
  rawparts=[p for c in candidates for p in (c.geoms if c.geom_type=='MultiPolygon' else [c]) if p.geom_type=='Polygon']
  lookup=[{(round(x,2),round(y,2)) for x,y,*_ in p.exterior.coords} for p in rawparts]
  localparts=list(g.geoms) if g.geom_type=='MultiPolygon' else [g];refined=[];hits=0
  for local in localparts:
   vertices={(round(x,2),round(y,2)) for x,y,*_ in local.exterior.coords}
   matches=[p for p,vs in zip(rawparts,lookup) if vertices<=vs]
   if matches:
    best=min(matches,key=lambda p:abs(p.area-local.area));refined.append(best.simplify(.025,preserve_topology=True));hits+=1
   else:refined.append(local)
  partsMatched+=hits
  if hits:matched+=1
  if hits<len(localparts):fallback.append(i)
  geom={'type':'MultiPolygon','coordinates':[mapping(p)['coordinates'] for p in refined]} if g.geom_type=='MultiPolygon' else mapping(refined[0])
  features.append({'type':'Feature','geometry':geom,'properties':{'index':i}})
 report[name]={**emit(name,{'type':'FeatureCollection','displayDetail':True,'features':features}),'matched':matched,'partsMatched':partsMatched,'fallback':fallback,'features':len(features)}
 if name=='world_2010.geojson':
  # Union removes contemporary internal borders from the neutral coast.
  land=unary_union([shape(f['geometry']).buffer(0) for f in up['features'] if f.get('geometry')]).simplify(.025,preserve_topology=True)
  report['land']=emit('land',{'type':'FeatureCollection','displayDetail':True,'features':[{'type':'Feature','geometry':mapping(land),'properties':{}}]})
 print(name,report[name]['gzipBytes'],matched,'/',len(features),flush=True)
(out/'manifest.json').write_text(json.dumps({'land':manifest['land'],'snapshots':{str(row['year']):manifest[row['file']] for row in json.loads((R/'data/snapshots.json').read_text())}},separators=(',',':'))+'\n')
(R/'data/DETAIL-SOURCES.md').write_text(f'''# TASK24 display detail\n\nSource: https://github.com/aourednik/historical-basemaps/tree/{commit}/geojson\nLicense: GPL-3.0, see LICENSE-historical-basemaps.txt (in this data directory).\nGenerated by scripts/v20-detail.py. Raw files are retained only in ignored artifacts/v20-upstream.\nSame NAME and exact subset of upstream vertices rounded to 0.01 degrees required for every retained polygon; unmatched parts retain local geometry. Parts absent from the local snapshot are never added. No names, dates, reviews or descriptions changed. Coordinates simplified at 0.025 degrees with topology preservation and rounded to 4 decimals. Neutral land is the dissolved 2010 baseline; this remains a physical orientation aid.\nFiles are explicit gzip, decoded in a Worker; lazy at zoom 4.5.\n''')
(R/'artifacts/v20-detail-sizes.json').write_text(json.dumps({'commit':commit,'layers':report},indent=2))

keep=set(manifest.values())
for p in out.glob('*.json.gz'):
 if p.name not in keep:p.unlink()
